import { createCanvas, loadImage } from "@napi-rs/canvas";
const img = await loadImage("src/game/assets/body-fixtures/fixture-sheet.png");
console.log("sheet", img.width, img.height);
const cv = createCanvas(64, 64);
const ctx = cv.getContext("2d");
ctx.drawImage(img, 0, 0, 128, 192, 0, 0, 64, 64);
const d = ctx.getImageData(0, 0, 64, 64).data;
let n = 0;
for (let i = 3; i < d.length; i += 4) if (d[i] > 16) n++;
console.log("drawn opaque px:", n, "of", 64*64);
