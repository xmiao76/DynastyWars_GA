/**
 * Render the five hero portraits as a contact sheet, at the sizes the game
 * actually shows them.
 *
 *   npm run dev            # in another terminal
 *   node scripts/facesheet.mjs
 *
 * Why this is a committed script rather than another throwaway in artifacts/:
 * every earlier face round judged the portraits at TEXTURE size, 216x240,
 * while the game never shows one above 136x152 and the HUD plate shows it at
 * 54x60 - a 1.6x to 4x downsample. Marks that carried the whole "this is a
 * face" impression at texture size vanished on screen. The sheet therefore
 * renders each portrait at its native size AND at all three display sizes.
 *
 * It pulls the real `portrait:<kind>` textures out of the running game rather
 * than re-deriving them, so what is judged is what ships - including the
 * renderer the owner actually gets from `npm run dev`, which is WebGL.
 *
 * The portrait textures are generated by SelectScene, so the script walks to
 * the select screen first; before that they do not exist.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { createCanvas, loadImage } from '@napi-rs/canvas'
import { chromium } from '@playwright/test'

// The callbacks below are serialised and run INSIDE the page, where `window`
// exists; this file itself is Node. eslint lints it as Node either way.
/* global window */

const URL = process.env.DW_URL ?? 'http://localhost:5176'
const OUT = 'artifacts/look/facesheet.png'
/** Logical display sizes, times RENDER_SCALE 2, from SelectScene and HudScene. */
const SHOWN = [
  ['select panel', 136, 152],
  ['roster thumb', 88, 96],
  ['HUD plate', 54, 60],
]

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 960, height: 540 } })
page.on('pageerror', (e) => console.error('PAGE ERROR', e.message))
await page.goto(`${URL}/?autopilot=1`, { waitUntil: 'networkidle' })
await page.waitForFunction(() => window.__DW__?.getSnapshot().scene === 'title')
await page.keyboard.press('Enter')
await page.waitForFunction(() => window.__DW__?.getSnapshot().scene === 'select')

const shots = await page.evaluate(() => {
  const tex = window.__DW_GAME__.textures
  const out = {}
  for (const key of tex.getTextureKeys()) {
    if (!key.startsWith('portrait:')) continue
    out[key.slice('portrait:'.length)] = tex.get(key).getSourceImage().toDataURL('image/png')
  }
  return out
})
await browser.close()

const kinds = Object.keys(shots)
if (kinds.length === 0) throw new Error('no portrait textures found - did the select screen load?')
console.log(`portraits: ${kinds.join(', ')}`)

const images = await Promise.all(kinds.map((k) => loadImage(shots[k])))
const W = images[0].width
const H = images[0].height
const pad = 14
const labels = 18
const rows = H + SHOWN.reduce((a, [, , h]) => a + h + 8, 0)
// A left gutter for the row labels: drawn at x=2 they landed on top of the
// first hero's column.
const gutter = 96
const sheet = createCanvas(gutter + kinds.length * (W + pad) + pad, rows + labels + pad * 2)
const ctx = sheet.getContext('2d')
ctx.fillStyle = '#1b1f27'
ctx.fillRect(0, 0, sheet.width, sheet.height)

kinds.forEach((kind, i) => {
  const x = gutter + pad + i * (W + pad)
  ctx.fillStyle = '#ffd700'
  ctx.font = 'bold 14px sans-serif'
  ctx.fillText(kind, x, labels - 4)
  ctx.drawImage(images[i], x, labels)
  let y = labels + H + 8
  for (const [, dw, dh] of SHOWN) {
    ctx.drawImage(images[i], x, y, dw, dh)
    y += dh + 8
  }
})
ctx.fillStyle = '#9ab0c0'
ctx.font = '12px sans-serif'
SHOWN.reduce((y, [name, , dh]) => {
  ctx.fillText(name, 8, y + 16)
  return y + dh + 8
}, labels + H + 8)

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, sheet.toBuffer('image/png'))
console.log(`wrote ${OUT} (${sheet.width}x${sheet.height})`)
